 *
 * Generates optimized robots.txt with:
 * - Smart crawl directives
 * - Proper sitemap references
 * - Crawl-delay for bots
 * - Blocking of low-value URLs
 *
 * @author      Michele Pietrafesa
 * @copyright   2024
 * @license     MIT
